"""
Coverage report of the files the model reads, from the data declarations.

The declarations (capri_data/schema/*.sql; as JSON in capri_data/schema/schema.json, generated by
tools/check/make_schema_json.py) give each data file its provenance (01_provenance.sql, from the pipeline's trace),
its checked notes and gaps (02_provenance_notes.sql) and the code that names it. This report lists, for every file
the model's code names (schema.json read_by.model), its cells, its non-zero cells and its origin, and adds up the
non-zero cells by origin. It changes no data. Run it before and after a data change: a fall in the cells of CAPRI
origin that a declaration change does not explain is a regression (the silent drops of the project's history:
maize, grassland, the livestock PMP terms). The tests capri_mod/tests/test_capri.py
test_schema_coverage_has_not_regressed and test_schema_declares_every_input_and_all_files_exist hold the floor.

Until 29 October 2026 the report read the hand-kept INPUT_SCHEMA.json (54 inputs, retired).

Usage
-----
    python tools/check/verify_schema.py                 # print the report
    python tools/check/verify_schema.py --json out.json # also write it
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]


def cell_coverage(path: Path) -> tuple[int, int]:
    """(live_cells, non_zero_cells) of the numeric columns of a CSV (first column as index); (0, 0) if unreadable."""
    try:
        df = pd.read_csv(path, index_col=0, float_precision="round_trip")
    except Exception:
        return 0, 0
    num = df.select_dtypes(include=[np.number])
    if num.empty:
        return 0, 0
    return int(num.notna().sum().sum()), int(((num != 0) & num.notna()).sum().sum())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--json", type=Path, default=None)
    args = ap.parse_args()
    tables = json.loads((args.root / "capri_data" / "schema" / "schema.json").read_text())["tables"]

    report = {"files": {}, "by_nature": {}, "issues": []}
    nz_by_nature = Counter()
    print(f"{'file':64s} {'cells':>8s} {'nonzero':>8s}  origin")
    print("-" * 100)
    for t in sorted(tables.values(), key=lambda t: t["file"]):
        if not t["read_by"]["model"]:
            continue
        f = args.root / t["file"]
        prov = t["provenance"] or {}
        nature = prov.get("nature", "none")
        if not f.exists():
            report["issues"].append(f"MISSING FILE: {t['file']}")
            continue
        live, nz = cell_coverage(f)
        nz_by_nature[nature] += nz
        gaps = [n["note"] for n in t["notes"] if n["kind"] == "gap"]
        report["files"][t["file"]] = {"live_cells": live, "nonzero_cells": nz, "nature": nature,
                                      "origins": prov.get("origins"), "builder": prov.get("builder"), "gaps": gaps}
        print(f"{t['file'][11:75]:64s} {live:8d} {nz:8d}  {nature}: {prov.get('origins', '')}")
    report["by_nature"] = dict(nz_by_nature)
    total = sum(nz_by_nature.values())
    capri = nz_by_nature["capri"] + nz_by_nature["capri-publication"]
    print("-" * 100)
    print(f"\n{len(report['files'])} files named in the model's code; non-zero cells by origin: {dict(nz_by_nature)}")
    if total:
        print(f"non-zero cells in files of CAPRI origin: {capri:,} of {total:,} ({capri / total:.1%}); the origin is "
              "the file's (a mixed file counts apart)")
    gaps = {f: v["gaps"] for f, v in report["files"].items() if v["gaps"]}
    if gaps:
        print("\nchecked gaps (02_provenance_notes.sql):")
        for f, g in gaps.items():
            print(f"  {f}: {' | '.join(g)}")
    if report["issues"]:
        print("\nISSUES:")
        for i in report["issues"]:
            print(f"  {i}")
    if args.json:
        args.json.write_text(json.dumps(report, indent=1))
        print(f"\nwritten: {args.json}")


if __name__ == "__main__":
    main()
